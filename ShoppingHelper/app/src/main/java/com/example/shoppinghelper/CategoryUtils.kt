    /**
     * Подбирает категорию по названию товара по встроенному справочнику.
     * Главным считается слово, которое стоит раньше: «Сок апельсиновый» — напиток,
     * а не фрукт, «Шоколад молочный» — сладости. Если ничего не подошло, возвращает null.
     */
    fun guessCategoryByKeywords(itemName: String): String? {
        val text = itemName.lowercase().replace('ё', 'е')
        if (text.isBlank()) return null

        // 1. Основы из нескольких слов («масло подсолн») ищутся во всей строке
        for ((category, stems) in keywords) {
            if (stems.any { it.contains(' ') && text.contains(normalize(it)) }) return category
        }

        // 2. Слова названия по порядку: «Молоко 3,2%» → ["молоко", "3,2%"]
        val words = text.split(' ', ',', '.', '-', '(', ')', '/').filter { it.isNotBlank() }
        for (word in words) {
            for ((category, stems) in keywords) {
                if (stems.any { !it.contains(' ') && word.startsWith(normalize(it)) }) return category
            }
        }
        return null
    }

    private fun normalize(stem: String) = stem.replace('ё', 'е')

